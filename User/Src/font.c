const uint8_t *Font6x8_GetGlyph(char character)
{
  uint8_t value = (uint8_t)character;
  if ((value < 0x20U) || (value > 0x7FU))
  {
    value = (uint8_t)'?';
  }
  return font6x8[value - 0x20U];
}

